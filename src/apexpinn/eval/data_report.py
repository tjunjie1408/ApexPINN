"""Pure G0 data-report builder. Reads the Gold build receipt, never fits or changes data."""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any


def _number(value: Any) -> str:
    return "Unknown" if value is None else f"{value:.6g}"


def build_data_report(receipt: Mapping[str, Any], *, source: str) -> str:
    """Render provenance, exclusions, fold counts and training-only proxy checks from one receipt."""
    coverage = receipt["coverage"]
    complete = coverage["configured_dev_events_complete"] and coverage["configured_folds_complete"]
    lines = [
        "# G0 data report",
        "",
        "Generated by apexpinn.eval.data_report; do not edit by hand.",
        "",
        f"Source: `{source}` (schema `{receipt['schema']}`); all counts and file hashes are `Observed`.",
        "Diagnostic ratios are `Inferred` from the stated formulas. No forecasting evaluation has run.",
        "",
        f"Coverage: **{'COMPLETE INPUT COVERAGE' if complete else 'PARTIAL'}**.",
        f"G0: **{receipt['g0_status']}**.",
        f"Gold dataset SHA-256: `{receipt['dataset_sha256']}`.",
        "",
        "This report supplies G0 evidence; a successful data build alone does not establish the gate.",
        "Partial builds never substitute fabricated training races for missing real circuits.",
        "",
        "## Source and scope",
        "",
        f"Conditions: phi={receipt['conditions']['phi']}; proxy={receipt['conditions']['proxy']}.",
        "The energy index is an acceleration-load proxy in m/s^2, not measured frictional energy.",
        "Min/max uses eligible scored training-circuit rows only. Test circuits and the temporal holdout",
        "never fit the transform or context means. Values outside its range are clipped and counted.",
        "A constant training range maps finite values to zero. Empty training folds are rejected.",
        "Context for an unseen circuit uses the global training mean, labeled explicitly as a fallback.",
        "",
        f"Missing configured development events: {', '.join(coverage['missing_dev_events']) or 'None'}.",
        "",
        "| Event | Bronze manifest SHA-256 |",
        "| :--- | :--- |",
    ]
    for event, info in sorted(receipt["inputs"].items()):
        label = " (crafted fixture)" if info["manifest"].get("fixture") else ""
        lines.append(f"| {event}{label} | `{info['manifest_sha256']}` |")
    lines += [
        "",
        "## O1 event eligibility",
        "",
        "Telemetry missing share uses all original laps. The boundary 20% is included; greater shares",
        "are rejected. Unknown telemetry status counts missing. Silver row filters are preserved.",
        "",
        "| Event | Dry verified | Missing telemetry share | Eligible | Reason |",
        "| :--- | :--- | ---: | :--- | :--- |",
    ]
    for event in receipt["event_eligibility"]:
        lines.append(
            f"| {event['session_id']} | {event['is_dry']} | "
            f"{_number(event['telemetry_missing_share'])} | {event['eligible']} | {event['reason']} |"
        )
    for fold, error in sorted(receipt["fold_failures"].items()):
        lines += ["", f"Fold {fold}: **FAILED**: {error}."]
    for fold, result in sorted(receipt["folds"].items()):
        stats = result["normalization"]
        lines += [
            "",
            f"## Fold {fold}",
            "",
            f"Rows: {result['rows']}; stints: {result['stints']};",
            f"Silver scored laps: {result['scored_laps']};",
            f"model-input laps: {result['model_input_laps']}; fitted training rows: {stats['n_train']}.",
            f"Training events: {', '.join(stats['training_events'])}.",
            f"Training range: [{_number(stats['lower'])}, {_number(stats['upper'])}].",
            f"Constant training range: {stats['constant_range']}.",
            f"Training-row fingerprint: `{stats['training_rows_sha256']}`.",
            "",
            "### Counts by assigned circuit fold",
            "",
            "| Circuit fold | Rows | Stints | Scored laps | Model-input laps |",
            "| :--- | ---: | ---: | ---: | ---: |",
        ]
        for population in result["fold_population"]:
            lines.append(
                f"| {population['split_fold']} | {population['rows']} | {population['stints']} | "
                f"{population['scored_laps']} | {population['model_input_laps']} |"
            )
        lines += [
            "",
            "### Exclusion counts",
            "",
            "Counts retain the first matching Silver reason; blank means scored.",
            "",
            "| Reason | Silver laps |",
            "| :--- | ---: |",
        ]
        lines += [
            f"| {reason or '(scored)'} | {count} |"
            for reason, count in sorted(result["exclusion_counts"].items())
        ]
        lines += ["", "| Feature quality reason | Laps |", "| :--- | ---: |"]
        lines += [
            f"| {reason or '(usable feature)'} | {count} |"
            for reason, count in sorted(result["feature_exclusion_counts"].items())
        ]
        lines += [
            "",
            "### Circuit q variance",
            "",
            "Variance uses normalized q on model-input rows, ddof=0. Test rows are descriptive only.",
            "",
            "| Circuit | Role | Laps | q mean | q variance | Clipped laps |",
            "| :--- | :--- | ---: | ---: | ---: | ---: |",
        ]
        for row in result["circuit_q_variance"]:
            lines.append(
                f"| {row['circuit']} | {row['role']} | {row['laps']} | {_number(row['q_mean'])} | "
                f"{_number(row['q_variance_ddof0'])} | {row['clipped_laps']} |"
            )
        l2 = result["l2_training_only"]
        lines += [
            "",
            "L2 training-only ratio = mean(within-stint q std, ddof=0) /",
            "std(training circuit q means, ddof=1). At least two training circuits are needed.",
            f"Ratio: {_number(l2['ratio'])}; L2 refuted (>0.1): {l2['limit_refuted']}.",
            "",
            "### Training-only O2 diagnostics",
            "",
            "These reuse the probe's event separation, drift/noise and within-stint/partial target",
            "correlation checks. A leak warning requires review; the proxy is never switched automatically.",
            f"O2 status: **{result['o2_status']}**.",
            "",
            "| Proxy | Laps | Between-event share | Within-stint corr(y) | Partial corr(y) | Leak warning |",
            "| :--- | ---: | ---: | ---: | ---: | :--- |",
        ]
        for name, row in sorted(result["training_proxy_checks"].items()):
            lines.append(
                f"| {name} | {row.get('n_laps', 0)} | {_number(row.get('between_event_share'))} | "
                f"{_number(row.get('corr_y_within_stint'))} | "
                f"{_number(row.get('partial_corr_y_given_lap'))} | {row.get('leak_warning', 'Unknown')} |"
            )
        lines += [
            "",
            "Full candidate diagnostics, source hashes and output hashes are in the source receipt.",
        ]
    lines += [
        "",
        "## Outstanding checks",
        "",
        "Complete remaining development extraction and eligibility/proxy validation before config freeze.",
        "Independently compare two complete rebuild hashes and run T9/T10 tests to assess G0.",
        "Broader predictive evaluation, holdout evaluation and deployment are NOT RUN.",
        "",
    ]
    return "\n".join(lines)
